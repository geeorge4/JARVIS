"""Lightweight, local conversation style selection."""
STYLES = {
    'Адаптивный': 'Подбирай тон по ситуации: при работе спокойный и деловой, в игре живой и дружеский.',
    'Спокойный': 'Общайся спокойно, терпеливо и без лишних эмоций.',
    'Дружеский': 'Общайся по-дружески; допустим лёгкий уместный юмор без насмешек.',
    'Деловой': 'Общайся сдержанно и по делу. Сначала результат, затем необходимые шаги.',
}
def instruction(prefs, prompt):
    style = prefs.get('personality', 'Адаптивный')
    text = STYLES.get(style, STYLES['Адаптивный'])
    if style == 'Адаптивный' and prefs.get('game_mode', False):
        text += ' Сейчас включён игровой режим: отвечай особенно кратко, не отвлекай от игры.'
    if any(word in prompt.casefold() for word in ('ошибк', 'error', 'не работает', 'сбой', 'bsod')):
        text += ' При разборе неисправностей используй серьёзный, спокойный тон без шуток.'
    return text + ' Стиль не меняет факты, доступные функции или правила выполнения команд.'
